package org.example;

/**
 * Типы стратегий генерации значений
 */
public enum GenerationType {
    /**
     * Автоматическая генерация базой данных (AUTO_INCREMENT/SERIAL)
     */
    IDENTITY,

    /**
     * Использование последовательности базы данных
     */
    SEQUENCE,

    /**
     * Генерация UUID на стороне приложения
     */
    UUID,

    /**
     * Значение генерируется базой данных, но не обязательно как IDENTITY
     */
    AUTO
}
